/// Choose the string for `lang` from the six provided, in the fixed order
/// English, German, Spanish, French, Russian, Brazilian Portuguese.
#[allow(clippy::too_many_arguments)]
fn pick(
    lang: Lang,
    en: &'static str,
    de: &'static str,
    es: &'static str,
    fr: &'static str,
    ru: &'static str,
    pt: &'static str,
) -> &'static str {
    match lang {
        Lang::En => en,
        Lang::De => de,
        Lang::Es => es,
        Lang::Fr => fr,
        Lang::Ru => ru,
        Lang::PtBr => pt,
    }
}

